    # ── retrying invocation primitives ───────────────────────────────────────
    def _invoke_unary(
        self,
        method: Callable[..., Any],
        rpc_name: str,
        request: Any,
        *,
        metadata: Metadata | None,
        timeout: float | None,
        retryable: bool,
    ) -> Any:
        attempt = 0
        while True:
            attempt += 1
            request_id = uuid.uuid4().hex
            try:
                return method(
                    request,
                    metadata=self._call_metadata(metadata, request_id),
                    timeout=self._timeout if timeout is None else timeout,
                )
            except grpc.RpcError as error:
                code = error.code()
                if retryable and self._retry.should_retry(code, attempt):
                    time.sleep(self._retry.backoff_for(attempt))
                    continue
                raise _map_error(rpc_name, error) from error

    def _invoke_server_streaming(
        self,
        method: Callable[..., Any],
        rpc_name: str,
        request: Any,
        *,
        metadata: Metadata | None,
        timeout: float | None,
        retryable: bool,
    ) -> Iterator[Any]:
        # Retry only applies before the first item is yielded; once streaming has
        # begun a partial replay is not safe, so we surface errors as they occur.
        attempt = 0
        while True:
            attempt += 1
            request_id = uuid.uuid4().hex
            stream = method(
                request,
                metadata=self._call_metadata(metadata, request_id),
                timeout=self._timeout if timeout is None else timeout,
            )
            iterator = iter(stream)
            try:
                first = next(iterator)
            except StopIteration:
                return
            except grpc.RpcError as error:
                code = error.code()
                if retryable and self._retry.should_retry(code, attempt):
                    time.sleep(self._retry.backoff_for(attempt))
                    continue
                raise _map_error(rpc_name, error) from error

            def _drain() -> Iterator[Any]:
                yield first
                try:
                    for item in iterator:
                        yield item
                except grpc.RpcError as error:
                    raise _map_error(rpc_name, error) from error

            return _drain()

    def _invoke_client_streaming(
        self,
        method: Callable[..., Any],
        rpc_name: str,
        request_iterator: Iterable[Any],
        *,
        metadata: Metadata | None,
        timeout: float | None,
    ) -> Any:
        # Client-streaming / bidi requests are never auto-retried: the request
        # iterator is generally not replayable.
        request_id = uuid.uuid4().hex
        try:
            return method(
                request_iterator,
                metadata=self._call_metadata(metadata, request_id),
                timeout=self._timeout if timeout is None else timeout,
            )
        except grpc.RpcError as error:
            raise _map_error(rpc_name, error) from error


