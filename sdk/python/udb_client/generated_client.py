class GeneratedClient:
    """Aggregate facade exposing one robustness client per UDB service.

    All sub-clients share the same channel/metadata/retry configuration, so a
    single :class:`GeneratedClient` covers every RPC across every service.
    """

    def __init__(self, target: str = "", metadata: Metadata | None = None, **kwargs: Any) -> None:
        self._kwargs = kwargs
        self._target = target
        self._metadata = metadata
        self.AnalyticsService: AnalyticsServiceClient = AnalyticsServiceClient(
            target, metadata, **kwargs
        )
        self.ApiKeyService: ApiKeyServiceClient = ApiKeyServiceClient(
            target, metadata, **kwargs
        )
        self.AuthnService: AuthnServiceClient = AuthnServiceClient(
            target, metadata, **kwargs
        )
        self.AuthzService: AuthzServiceClient = AuthzServiceClient(
            target, metadata, **kwargs
        )
        self.NotificationService: NotificationServiceClient = NotificationServiceClient(
            target, metadata, **kwargs
        )
        self.TenantService: TenantServiceClient = TenantServiceClient(
            target, metadata, **kwargs
        )
        self.DataBroker: DataBrokerClient = DataBrokerClient(
            target, metadata, **kwargs
        )

    def bind_metadata(self, metadata: Metadata) -> None:
        self._metadata = metadata
        self.AnalyticsService.bind_metadata(metadata)
        self.ApiKeyService.bind_metadata(metadata)
        self.AuthnService.bind_metadata(metadata)
        self.AuthzService.bind_metadata(metadata)
        self.NotificationService.bind_metadata(metadata)
        self.TenantService.bind_metadata(metadata)
        self.DataBroker.bind_metadata(metadata)

    def close(self) -> None:
        self.AnalyticsService.close()
        self.ApiKeyService.close()
        self.AuthnService.close()
        self.AuthzService.close()
        self.NotificationService.close()
        self.TenantService.close()
        self.DataBroker.close()

    def __enter__(self) -> "GeneratedClient":
        return self

    def __exit__(self, *_: object) -> None:
        self.close()
