"""``udb`` CLI launcher bundled with the UDB Python SDK.

Generated by `udb sdk generate` from the embedded proto descriptor set. Edit the template under sdk-templates/<lang>/, not this file.

Installing ``udb-client`` exposes a console script named ``udb`` (wired in
``pyproject.toml`` as ``udb = "udb_client._cli:main"``). Running it locates a
version-matched ``udb`` binary and execs it, transparently forwarding all
arguments and the exit code. Resolution order:

  1. An ``udb`` binary whose ``--version`` matches 0.6.16 already on
     ``PATH`` (but not this launcher itself). Every PATH match is tried in
     order; this launcher and any other launcher copy or console-script shim
     are skipped, each probe has a 5 s timeout, and a launcher started by
     another launcher (``UDB_LAUNCHER_ACTIVE`` set) skips PATH entirely, so a
     launcher can never recurse into itself.
  2. A previously downloaded binary cached for this version under the per-user
     cache dir.
  3. The matching release asset downloaded from
     ``https://github.com/fahara02/udb/releases/tag/v0.6.16`` for the
     current OS/arch, cached, then exec'd.

Set ``UDB_BIN`` to force a specific binary, or ``UDB_SKIP_DOWNLOAD=1`` to forbid
network fetches (PATH/cache only).
"""

from __future__ import annotations

import os
import platform
import hashlib
import shutil
import stat
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

UDB_VERSION = "0.6.16"
PROTOCOL_VERSION = "1.0.0"
_REPO = "fahara02/udb"
_RELEASE_BASE = f"https://github.com/{_REPO}/releases/download/v{UDB_VERSION}"


def _exe_suffix() -> str:
    return ".exe" if os.name == "nt" else ""


def _asset_name() -> str:
    """GitHub release asset name for this platform.

    Convention: ``udb-<os>-<arch>[-<variant>]<ext>`` (e.g.
    ``udb-linux-amd64``, ``udb-windows-amd64.exe``, ``udb-darwin-arm64``).

    The published release attaches RAW binaries (no version in the name, no
    archive). ``<os>`` is linux|darwin|windows, ``<arch>`` is amd64|arm64.
    ``UDB_BIN_VARIANT`` appends ``-<variant>`` unless unset/empty/``portable``
    (e.g. ``full`` -> ``udb-linux-amd64-full``). ``<ext>`` is ``.exe`` on
    Windows, empty elsewhere.
    """

    system = platform.system().lower()
    os_tag = {"linux": "linux", "darwin": "darwin", "windows": "windows"}.get(system, system)
    machine = platform.machine().lower()
    arch = {
        "x86_64": "amd64",
        "amd64": "amd64",
        "aarch64": "arm64",
        "arm64": "arm64",
    }.get(machine, machine)
    variant = ""
    raw_variant = (os.environ.get("UDB_BIN_VARIANT") or "").strip()
    if raw_variant and raw_variant.lower() != "portable":
        variant = f"-{raw_variant}"
    return f"udb-{os_tag}-{arch}{variant}{_exe_suffix()}"


def _cache_dir() -> Path:
    if os.name == "nt":
        base = os.environ.get("LOCALAPPDATA") or str(Path.home() / "AppData" / "Local")
    else:
        base = os.environ.get("XDG_CACHE_HOME") or str(Path.home() / ".cache")
    path = Path(base) / "udb" / "bin" / UDB_VERSION
    path.mkdir(parents=True, exist_ok=True)
    return path


# Recursion guard. Every child this launcher starts (a ``--version`` probe or
# the final exec) gets UDB_LAUNCHER_ACTIVE=1. A launcher that starts with it
# already set is nested (a PATH candidate was itself a launcher) and never
# probes PATH, so one invocation can start only a bounded number of processes.
_LAUNCHER_ENV = "UDB_LAUNCHER_ACTIVE"
_PROBE_TIMEOUT_S = 5
# A launcher script / console-script shim is small; the real binary is tens of MB.
_SHIM_SNIFF_MAX_BYTES = 2 * 1024 * 1024
# A console script for this package imports ``udb_client._cli``; any launcher
# copy names the guard variable.
_LAUNCHER_MARKERS = (_LAUNCHER_ENV.encode(), b"udb_client")


def _child_env() -> dict[str, str]:
    env = dict(os.environ)
    env[_LAUNCHER_ENV] = "1"
    return env


def _is_nested_launcher() -> bool:
    return bool(os.environ.get(_LAUNCHER_ENV))


def _binary_version_matches(binary: str) -> bool:
    try:
        out = subprocess.run(
            [binary, "--version"],
            capture_output=True,
            text=True,
            timeout=_PROBE_TIMEOUT_S,
            env=_child_env(),
            stdin=subprocess.DEVNULL,
        )
    except (OSError, subprocess.SubprocessError):
        return False
    return UDB_VERSION in (out.stdout + out.stderr)


def _norm(path: str) -> str:
    resolved = os.path.realpath(path)
    return os.path.normcase(resolved)


def _self_paths() -> set[str]:
    """Paths that are this launcher: the console script and this module."""

    selves: set[str] = set()
    for raw in (sys.argv[0] if sys.argv else "", __file__):
        if not raw:
            continue
        selves.add(_norm(raw))
        # A Windows console script runs as ``udb.exe`` while argv[0] may lack
        # the suffix (and the other way round).
        if os.name == "nt":
            root, ext = os.path.splitext(raw)
            selves.add(_norm(root if ext.lower() == ".exe" else raw + ".exe"))
    return selves


def _is_launcher_candidate(candidate: str) -> bool:
    """True when probing ``candidate`` would run a udb launcher again."""

    try:
        real = _norm(candidate)
    except OSError:
        return True
    if real in _self_paths():
        return True
    try:
        size = os.path.getsize(real)
        if size <= _SHIM_SNIFF_MAX_BYTES:
            with open(real, "rb") as fh:
                data = fh.read()
            if any(marker in data for marker in _LAUNCHER_MARKERS):
                return True
    except OSError:
        return True
    return False


def _path_candidates() -> list[str]:
    """Every ``udb`` on PATH in PATH order (all matches, not only the first)."""

    found: list[str] = []
    seen: set[str] = set()
    for directory in (os.environ.get("PATH") or "").split(os.pathsep):
        if not directory:
            continue
        hit = shutil.which("udb", path=directory)
        if hit and os.path.normcase(hit) not in seen:
            seen.add(os.path.normcase(hit))
            found.append(hit)
    return found


def _path_binary() -> str | None:
    """An ``udb`` on PATH that is not a launcher and matches the version."""

    if _is_nested_launcher():
        # A nested launcher never probes PATH: that bounds the recursion.
        return None
    for candidate in _path_candidates():
        if _is_launcher_candidate(candidate):
            continue
        if _binary_version_matches(candidate):
            return candidate
    return None


def _cached_binary() -> str | None:
    candidate = _cache_dir() / f"udb{_exe_suffix()}"
    return str(candidate) if candidate.is_file() else None


def _sha256_file(path: str) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _fetch_text(url: str) -> str | None:
    try:
        with urllib.request.urlopen(url, timeout=20) as resp:
            return resp.read().decode("utf-8")
    except Exception:
        return None


def _expected_sha_from_manifest(text: str, asset: str) -> str | None:
    asset_base = os.path.basename(asset)
    fallback: str | None = None
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) == 1:
            fallback = parts[0].lower().lstrip("*")
            continue
        digest = parts[0].lower()
        filename = parts[1].lstrip("*")
        if filename == asset or os.path.basename(filename) == asset_base:
            return digest
    return fallback


def _verify_checksum(path: str, asset: str) -> None:
    if os.environ.get("UDB_SKIP_CHECKSUM"):
        return
    urls = [
        f"{_RELEASE_BASE}/{asset}.sha256",
        f"{_RELEASE_BASE}/SHA256SUMS",
        f"{_RELEASE_BASE}/sha256sums.txt",
    ]
    for url in urls:
        text = _fetch_text(url)
        if not text:
            continue
        expected = _expected_sha_from_manifest(text, asset)
        if not expected:
            continue
        actual = _sha256_file(path)
        if actual.lower() != expected.lower():
            raise SystemExit(
                f"udb: checksum mismatch for {asset}: expected {expected}, got {actual}"
            )
        return
    sys.stderr.write(f"udb: warning: checksum manifest unavailable for {asset}\n")


def _download_binary() -> str:
    if os.environ.get("UDB_SKIP_DOWNLOAD"):
        raise SystemExit(
            f"udb {UDB_VERSION} binary not found and UDB_SKIP_DOWNLOAD is set. "
            f"Install it from {_RELEASE_BASE} or set UDB_BIN."
        )
    url = f"{_RELEASE_BASE}/{_asset_name()}"
    dest = _cache_dir() / f"udb{_exe_suffix()}"
    tmp_fd, tmp_path = tempfile.mkstemp(dir=str(_cache_dir()))
    os.close(tmp_fd)
    try:
        sys.stderr.write(f"udb: downloading {url}\n")
        with urllib.request.urlopen(url) as resp, open(tmp_path, "wb") as out:
            shutil.copyfileobj(resp, out)
        _verify_checksum(tmp_path, _asset_name())
        mode = os.stat(tmp_path).st_mode
        os.chmod(tmp_path, mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        os.replace(tmp_path, dest)
    except Exception as exc:  # noqa: BLE001 - surface a clean CLI error
        try:
            os.unlink(tmp_path)
        except OSError:
            pass
        raise SystemExit(
            f"udb: failed to download {url}: {exc}\n"
            f"Install the binary manually from {_RELEASE_BASE} or set UDB_BIN."
        ) from exc
    return str(dest)


def _resolve_binary() -> str:
    forced = os.environ.get("UDB_BIN")
    if forced:
        return forced
    return _path_binary() or _cached_binary() or _download_binary()


def main(argv: list[str] | None = None) -> int:
    """Locate and exec the version-matched ``udb`` binary, forwarding args."""

    args = list(sys.argv[1:] if argv is None else argv)
    binary = _resolve_binary()
    env = _child_env()
    if os.name == "nt":
        # exec semantics on Windows are unreliable; spawn and propagate.
        return subprocess.run([binary, *args], env=env).returncode
    os.execve(binary, [binary, *args], env)
    return 0  # unreachable on POSIX


if __name__ == "__main__":
    raise SystemExit(main())
